function tierValue(index, total, min, max) {
  if (total <= 1) return min;
  const t = index / (total - 1);
  const curved = Math.pow(t, 1.65);
  return Math.max(min, Math.round(min + (max - min) * curved));
}

function flattenSemanticTitles(category, count) {
  const bands = SEMANTIC_TITLES[category];
  if (!bands?.length) {
    throw new Error(`[ACHIEVEMENTS] Нет названий для категории ${category}`);
  }
  const flat = bands.flat();
  if (flat.length < count) {
    throw new Error(`[ACHIEVEMENTS] Недостаточно названий для ${category}: ${flat.length}/${count}`);
  }
  return flat.slice(0, count);
}

function pickSemanticEmoji(category, index) {
  const band = Math.floor(index / 10);
  const emojis = BAND_EMOJI[category] || ['🏅'];
  return emojis[Math.min(band, emojis.length - 1)];
}

function ensureGlobalUniqueName(name, category, usedNames) {
  const label = CATEGORY_META[category]?.label || category;
  let candidate = name.trim();
  if (!usedNames.has(candidate)) {
    usedNames.add(candidate);
    return candidate;
  }
  candidate = `${name.trim()} · ${label}`;
  if (!usedNames.has(candidate)) {
    usedNames.add(candidate);
    return candidate;
  }
  let suffix = 2;
  while (usedNames.has(`${name.trim()} · ${suffix}`)) suffix += 1;
  candidate = `${name.trim()} · ${suffix}`;
  usedNames.add(candidate);
  return candidate;
}

function buildTierAchievements(category, count, usedNames) {
  const range = TIER_RANGES[category];
  const titles = flattenSemanticTitles(category, count);
  const items = {};
  const tiers = [];
  let prev = 0;

  for (let i = 0; i < count; i++) {
    let threshold = tierValue(i, count, range.min, range.max);
    if (threshold <= prev) threshold = prev + 1;
    prev = threshold;

    const key = `${category}_t${String(i + 1).padStart(3, '0')}`;
    items[key] = {
      name: ensureGlobalUniqueName(titles[i], category, usedNames),
      emoji: pickSemanticEmoji(category, i),
      category,
      kind: 'tier',
      threshold,
      band: PROGRESS_BANDS[Math.min(Math.floor(i / 10), PROGRESS_BANDS.length - 1)],
    };
    tiers.push({ key, threshold });
  }

  return { items, tiers };
}

function buildCatalog() {
  const achievements = { ...SPECIAL_ACHIEVEMENTS };
  const tiersByCategory = {};
  const usedNames = new Set(Object.values(SPECIAL_ACHIEVEMENTS).map((a) => a.name));

  for (const category of Object.keys(CATEGORY_META)) {
    const { items, tiers } = buildTierAchievements(category, CATEGORY_META[category].count, usedNames);
    Object.assign(achievements, items);
    tiersByCategory[category] = tiers;
  }

  const total = Object.keys(achievements).length;
  if (total !== 1000) {
    throw new Error(`[ACHIEVEMENTS] Ожидалось 1000 достижений, получено ${total}`);
  }

  return { achievements, tiersByCategory };
}

